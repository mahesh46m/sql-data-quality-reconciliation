"""Build the demo DB, run every check in sql/checks, print and save results."""
import glob, os, sqlite3, subprocess, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
db = "dq_demo.db"
if os.path.exists(db):
    os.remove(db)
subprocess.run([sys.executable, "scripts/generate_seed.py", db], check=True)

con = sqlite3.connect(db)
out = ["# Sample output\n", "Generated by `python scripts/run_checks.py` (seed 42, synthetic data).\n"]
for path in sorted(glob.glob("sql/checks/*.sql")):
    sql = open(path).read()
    title = sql.splitlines()[0].lstrip("- ").strip()
    cur = con.execute(sql)
    cols = [c[0] for c in cur.description]
    rows = cur.fetchall()
    out.append(f"\n## {title}\n\n**Rows flagged: {len(rows)}**\n")
    if rows:
        out.append("| " + " | ".join(cols) + " |")
        out.append("|" + "---|" * len(cols))
        for r in rows[:5]:
            out.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
        if len(rows) > 5:
            out.append(f"\n_(first 5 of {len(rows)} shown)_")
    print(f"{os.path.basename(path):40s} {len(rows)} rows")
open("sample_output.md", "w").write("\n".join(out) + "\n")
print("wrote sample_output.md")
